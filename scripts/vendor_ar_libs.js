// scripts/vendor_ar_libs.js
// Copies the pinned, MIT-licensed browser libraries used by the dedicated AR page (ar.html) — GLTFLoader +
// decoders for the 3D view and USDZExporter for AR Quick Look conversion —
// from node_modules into js/vendor/. Re-run after bumping the pinned devDependency versions:
//   npm install && node scripts/vendor_ar_libs.js
// The vendored copies are committed so Cloudflare Pages / server.js serve them first-party
// (no runtime CDN dependency, works with a strict CSP).

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const threeRoot = path.join(root, 'node_modules', 'three');
const outThree = path.join(root, 'js', 'vendor', 'three');

const threePkg = require(path.join(threeRoot, 'package.json'));

const ADDONS = [
  'loaders/GLTFLoader.js',
  'loaders/DRACOLoader.js',
  'loaders/KTX2Loader.js',
  'libs/meshopt_decoder.module.js',
  'libs/ktx-parse.module.js',
  'libs/zstddec.module.js',
  'libs/basis/basis_transcoder.js',
  'libs/basis/basis_transcoder.wasm',
  'libs/draco/gltf/draco_decoder.js',
  'libs/draco/gltf/draco_decoder.wasm',
  'libs/draco/gltf/draco_wasm_wrapper.js',
  'controls/OrbitControls.js',
  'environments/RoomEnvironment.js',
  'exporters/USDZExporter.js',
  'libs/fflate.module.js',
  'utils/BufferGeometryUtils.js',
  'utils/WorkerPool.js',
  'math/ColorSpaces.js'
];

function copy(src, dst) {
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.copyFileSync(src, dst);
}

fs.rmSync(outThree, { recursive: true, force: true });
copy(path.join(threeRoot, 'build', 'three.module.min.js'), path.join(outThree, 'three.module.min.js'));
copy(path.join(threeRoot, 'LICENSE'), path.join(outThree, 'LICENSE'));
for (const rel of ADDONS) {
  copy(path.join(threeRoot, 'examples', 'jsm', rel), path.join(outThree, 'addons', rel));
}

const qrSrc = path.join(root, 'node_modules', 'qrcode-generator');
const qrPkg = require(path.join(qrSrc, 'package.json'));
copy(path.join(qrSrc, 'qrcode.js'), path.join(root, 'js', 'vendor', 'qrcode', 'qrcode.js'));
// qrcode-generator embeds its MIT license in the qrcode.js header (no separate LICENSE file is published).

fs.writeFileSync(path.join(root, 'js', 'vendor', 'VERSIONS.json'), JSON.stringify({
  three: threePkg.version,
  'qrcode-generator': qrPkg.version,
  note: 'Generated by scripts/vendor_ar_libs.js — do not edit by hand.'
}, null, 2) + '\n');

console.log(`Vendored three@${threePkg.version} (${ADDONS.length} addons) and qrcode-generator@${qrPkg.version} into js/vendor/`);
